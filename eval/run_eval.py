"""Planted-defect eval for the interop checker. Writes eval/results.md.

Start from healthy stacks (a CDP shares an identifier with every tool), plant one known defect,
and check the checker reports exactly that defect. Clean stacks measure false alarms.
Defects: ISOLATE (cut one tool off), SPLIT (two clusters with no shared id), DEMOTE_HUB (CDP no longer
reaches one tool; detected when the checker stops naming the CDP as the identity hub), CRM_ADS_CUT (CRM/email cannot reach ad platforms).
"""
import copy
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "src"))
from interop_checker import analyze  # noqa: E402

rng = random.Random(11)
IDS = ["email_hash", "cookie_id", "device_id", "phone", "crm_contact_id", "ip_address"]
CATS = ["crm", "email_platform", "ad_platform", "web_analytics", "attribution"]


def healthy_stack():
    n = rng.randint(4, 8)
    tools = [{"name": "CDP", "category": "cdp", "ids": list(IDS[:5])}]
    cats = [rng.choice(CATS) for _ in range(n - 1)]
    cats[0], cats[1] = "crm", "ad_platform"  # ensure the CRM/ads rule is testable
    for i, c in enumerate(cats):
        tools.append({"name": "%s%d" % (c, i), "category": c, "ids": rng.sample(IDS[:5], rng.randint(1, 3))})
    return tools


def isolate(tools):
    t = copy.deepcopy(tools)
    k = rng.randrange(1, len(t))
    others = {x for j, o in enumerate(t) if j != k for x in o["ids"]}
    free = [i for i in IDS if i not in others] or None
    if free is None:  # every id is used elsewhere: rewrite others to avoid ip_address, give it only to the victim
        for j, o in enumerate(t):
            o["ids"] = [x for x in o["ids"] if x != "ip_address"] or ["email_hash"]
        free = ["ip_address"]
    t[k]["ids"] = [free[0]]
    return t, t[k]["name"]


def split(tools):
    t = copy.deepcopy(tools)
    half = len(t) // 2
    for j, o in enumerate(t):
        o["ids"] = [x for x in o["ids"] if x in (("email_hash", "phone", "crm_contact_id") if j < half else ("cookie_id", "device_id", "ip_address"))]
        if not o["ids"]:
            o["ids"] = ["email_hash"] if j < half else ["cookie_id"]
    return t, None


def demote_hub(tools):
    t = copy.deepcopy(tools)
    victim = rng.randrange(1, len(t))
    others = {x for j, o in enumerate(t) if j not in (0, victim) for x in o["ids"]}
    cdp_ids = set(t[0]["ids"])
    # give victim an id the CDP lacks but another tool shares, so victim is connected but not to the CDP
    t[0]["ids"] = [x for x in t[0]["ids"] if x != "ip_address"]
    t[victim]["ids"] = ["ip_address"]
    t[(victim % (len(t) - 1)) + 1]["ids"] = list(set(t[(victim % (len(t) - 1)) + 1]["ids"]) | {"ip_address"}) if (victim % (len(t) - 1)) + 1 != victim else t[victim]["ids"]
    return t, None


def crm_ads_cut(tools):
    """Sever every path between CRM/email tools and ad platforms (CDP and others stay on the CRM side)."""
    t = copy.deepcopy(tools)
    side_a, side_b = ("email_hash", "phone", "crm_contact_id"), ("cookie_id", "device_id", "ip_address")
    for o in t:
        keep = side_b if o["category"] == "ad_platform" else side_a
        o["ids"] = [x for x in o["ids"] if x in keep] or [keep[0]]
    return t, None


CASES = {
    "ISOLATE": (isolate, "ISOLATED_TOOL"),
    "SPLIT": (split, "SPLIT_CLUSTERS"),
    "DEMOTE_HUB": (demote_hub, "CDP_NOT_HUB"),
    "CRM_ADS_CUT": (crm_ads_cut, "CRM_ADS_DISCONNECTED"),
}
N = 100
rows = []
worse = 0
for name, (fn, code) in CASES.items():
    detected = named = score_up = 0
    for _ in range(N):
        base = healthy_stack()
        before = analyze(base)
        planted, victim = fn(base)
        after = analyze(planted)
        got = {f["code"] for f in after["flags"]}
        if code == "CDP_NOT_HUB":  # pass if the checker no longer names the CDP as the identity hub
            got.add("CDP_NOT_HUB") if not any(f["code"] == "IDENTITY_HUB" and f.get("tool") == "CDP" for f in after["flags"]) else None
        detected += code in got
        if victim is not None:
            named += any(f.get("tool") == victim for f in after["flags"] if f["code"] == code)
        score_up += after["score"] >= before["score"]
    rows.append((name, code, detected, named if name == "ISOLATE" else None, score_up))

false_alarms = {c: 0 for _, (_, c) in CASES.items()}
healthy_hub_ok = 0
for _ in range(N):
    r = analyze(healthy_stack())
    got = {f["code"] for f in r["flags"]}
    for c in false_alarms:
        if c == "CDP_NOT_HUB":
            false_alarms[c] += any(f["code"] == "IDENTITY_HUB" and f.get("tool") == "CDP" for f in r["flags"]) is False
        else:
            false_alarms[c] += c in got
    healthy_hub_ok += "IDENTITY_HUB" in got

lines = ["# Eval results: interop checker (planted defects)", "",
         "Generated by `eval/run_eval.py`, seeded. %d planted stacks per defect, %d clean controls." % (N, N), "",
         "| Planted defect | Expected flag | Detected | Correct tool named | Score did not drop |", "|---|---|---|---|---|"]
for name, code, det, nm, up in rows:
    lines.append("| %s | `%s` | %d/%d | %s | %d/%d |" % (name, code, det, N, ("%d/%d" % (nm, N)) if nm is not None else "n/a", up, N))
lines += ["", "**False alarms on %d clean stacks (CDP shares an id with every tool):**" % N, ""]
for c, k in false_alarms.items():
    lines.append("- `%s`: %d/%d" % (c, k, N))
lines += ["", "- Clean stacks identified with an identity hub: %d/%d" % (healthy_hub_ok, N), "",
          "## Limits", "",
          "Defects are synthetic and the checker is rule-based, so detection should be near-perfect; the value of this eval",
          "is catching rule regressions and measuring false alarms. It does not show that a stack's real identity-resolution quality",
          "matches the score. That needs a real stack audited by a human (join rates between systems), which is the next step.", ""]
open(os.path.join(HERE, "results.md"), "w").write("\n".join(lines))
print("\n".join(lines))
